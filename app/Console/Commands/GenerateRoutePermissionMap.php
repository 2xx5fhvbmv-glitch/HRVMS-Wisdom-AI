<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Routing\Route;
use Illuminate\Support\Facades\DB;

/**
 * X-01 deny-by-default prep (report-only): infers a config/route_permissions.php map entry for every
 * resort-portal route (one behind the checkResortPermission middleware) that has neither its own
 * module_pages row nor a hand-written map entry, and writes them to config/route_permissions_generated.php.
 * Routes it cannot place go to config/route_permissions_unmapped.php with the reason (they keep logging
 * UNMAPPED_ROUTE). Reads the router and module_pages only; never touches the DB.
 *
 *   php artisan routes:generate-permission-map           (dry run: counts)
 *   php artisan routes:generate-permission-map --write   (rewrite both generated files)
 *
 * Re-run after adding routes or module_pages rows. Hand-written entries in route_permissions.php always
 * win over generated ones; to correct a generated entry, hand-write it there.
 */
class GenerateRoutePermissionMap extends Command
{
    protected $signature = 'routes:generate-permission-map {--write : Rewrite config/route_permissions_generated.php and _unmapped.php}';
    protected $description = 'Infer route_permissions map entries for portal routes without a module_pages row (report-only prep).';

    /** Every logged-in portal user needs these (own profile/password/notifications, landing dashboards, global search, staff chat). */
    public const SELF_SERVICE = [
        '/^resort\.logout$/', '/^resort\.user\.profile$/', '/^resort\.Updateuser\.profile$/', '/^resort\.profile\./',
        '/^resort\.Mark\.Notification/', '/^resort\.adminBroadcast\.dismiss$/', '/^resort\.search\.index$/',
        '/^resort\.master\.\w+_dashboard$/', '/^resort\.getMenuData$/', '/^resort\.Page\.Permission$/',   // last two: bypassed in Common anyway
        '/^resort\.chat\./', '/^resort\.wisdom\./',
        '/^resort\.wai[-_.]?guide/i', '/broadcasting/i',
    ];

    public function handle(): int
    {
        $r = self::build();
        $this->table(['', 'routes'], [
            ['portal routes (named)', $r['total']],
            ['own module_pages row', $r['pageRows']],
            ['hand-mapped', $r['hand']],
            ['generated (owner page)', count($r['generated']) - $r['selfService']],
            ['generated any_authenticated', $r['selfService']],
            ['left unmapped', count($r['unmapped'])],
        ]);
        $this->line('Generated by rule: ' . json_encode(array_count_values(array_column($r['rules'], 0))));
        $this->line('Generated ticks: ' . json_encode(array_count_values(array_map(fn ($e) => $e[1], $r['generated']))));
        foreach ($r['unmapped'] as $name => $why) {
            $this->line("  unmapped: $name — $why");
        }

        if (!$this->option('write')) {
            $this->comment('Dry run. Pass --write to rewrite config/route_permissions_generated.php.');
            return self::SUCCESS;
        }

        $lines = [];
        foreach ($r['generated'] as $name => [$owner, $tick]) {
            $lines[] = sprintf("    %s => [%s, %s], // %s", var_export($name, true), var_export($owner, true), var_export($tick, true), $r['rules'][$name][1]);
        }
        file_put_contents(config_path('route_permissions_generated.php'), "<?php\n\n"
            . "// GENERATED by `php artisan routes:generate-permission-map --write` — do not edit by hand; hand-write an\n"
            . "// override in config/route_permissions.php instead (hand-written entries win). Comment = inference rule.\n\n"
            . "return [\n" . implode("\n", $lines) . "\n];\n");

        $lines = [];
        foreach ($r['unmapped'] as $name => $why) {
            $lines[] = sprintf("    %s => %s,", var_export($name, true), var_export($why, true));
        }
        file_put_contents(config_path('route_permissions_unmapped.php'), "<?php\n\n"
            . "// GENERATED by `php artisan routes:generate-permission-map --write`. Portal routes deliberately left OUT of\n"
            . "// the route_permissions map (no owner page could be inferred and the route is not self-service). They keep\n"
            . "// logging UNMAPPED_ROUTE and would be DENIED if enforce_unmapped were true — give each a module_pages row or\n"
            . "// a hand-written map entry before flipping it. route name => reason.\n\n"
            . "return [\n" . implode("\n", $lines) . "\n];\n");

        $this->info('Wrote config/route_permissions_generated.php (' . count($r['generated']) . ') and config/route_permissions_unmapped.php (' . count($r['unmapped']) . ').');
        return self::SUCCESS;
    }

    /** Named routes the checkResortPermission middleware runs on, keyed by name (last definition wins, as in the router). */
    public static function portalRoutes(): array
    {
        $out = [];
        foreach (app('router')->getRoutes() as $route) {
            if ($route->getName() && in_array('checkResortPermission', $route->middleware(), true)
                && !in_array('checkResortPermission', $route->excludedMiddleware(), true)) {
                $out[$route->getName()] = $route;
            }
        }
        return $out;
    }

    /** internal_route => module_pages row, the same rows Common::checkRouteWisePermission() matches (menu page wins). */
    public static function pageRows(): array
    {
        $rows = [];
        foreach (DB::table('module_pages')->where('type', 'normal')->whereIn('TypeOfPage', ['InsideOfMenu', 'InsideOfPage'])
            ->whereNotNull('internal_route')->orderByRaw("TypeOfPage = 'InsideOfMenu' DESC")->orderBy('id')
            ->get(['id', 'Module_Id', 'TypeOfPage', 'internal_route']) as $p) {
            $rows[$p->internal_route] ??= $p;
        }
        return $rows;
    }

    /** The hand-written part of the map: config entries not coming (unchanged) from the generated file. */
    public static function handMap(): array
    {
        $file = config_path('route_permissions_generated.php');
        $generated = is_file($file) ? require $file : [];
        return array_filter(config('route_permissions.map', []), fn ($v, $k) => ($generated[$k] ?? null) !== $v, ARRAY_FILTER_USE_BOTH);
    }

    public static function build(): array
    {
        $routes = self::portalRoutes();
        $pages = self::pageRows();
        $hand = self::handMap();

        // Owner candidates: page rows whose route exists, with the controller/URI that serves them.
        $cands = [];
        foreach ($pages as $name => $p) {
            if (isset($routes[$name])) {
                $cands[] = ['name' => $name, 'menu' => $p->TypeOfPage === 'InsideOfMenu', 'id' => $p->id,
                    'class' => self::controller($routes[$name])[0], 'method' => self::controller($routes[$name])[1],
                    'uri' => explode('/', $routes[$name]->uri())];
            }
        }

        $generated = $rules = $unmapped = [];
        $pageRows = $handCount = $self = 0;
        foreach ($routes as $name => $route) {
            if (isset($pages[$name])) { $pageRows++; continue; }
            if (isset($hand[$name])) { $handCount++; continue; }

            if (self::isSelfService($name)) {
                $generated[$name] = ['*', 'any_authenticated'];
                $rules[$name] = ['self', 'self-service'];
                $self++;
                continue;
            }
            [$owner, $rule] = self::inferOwner($name, $route, $cands);
            if ($owner === null) {
                $unmapped[$name] = 'no module_pages row shares its name prefix, controller or URL prefix (' . $route->uri() . ')';
                continue;
            }
            $generated[$name] = [$owner, self::inferTick($name, $route)];
            $rules[$name] = [$rule, $rule];
        }
        ksort($generated);
        ksort($unmapped);

        return ['total' => count($routes), 'pageRows' => $pageRows, 'hand' => $handCount, 'selfService' => $self,
            'generated' => $generated, 'rules' => $rules, 'unmapped' => $unmapped];
    }

    public static function isSelfService(string $name): bool
    {
        foreach (self::SELF_SERVICE as $re) {
            if (preg_match($re, $name)) {
                return true;
            }
        }
        return false;
    }

    /** [ownerRoute|null, rule] — strict name prefix, same controller, shared name prefix, URL prefix, controller folder. */
    public static function inferOwner(string $name, Route $route, array $cands): array
    {
        [$class] = self::controller($route);
        $seg = explode('.', $name);
        $uri = explode('/', $route->uri());
        $pick = function (array $list, string $preferRe) {
            usort($list, fn ($a, $b) => [$b['score'], !$a['menu'], !preg_match($preferRe, $a['method'] . ' ' . $a['name']), $a['id']]
                <=> [$a['score'], !$b['menu'], !preg_match($preferRe, $b['method'] . ' ' . $b['name']), $b['id']]);
            return $list[0]['name'] ?? null;
        };
        $common = function (array $a, array $b) {
            $n = 0;
            while (isset($a[$n], $b[$n]) && strcasecmp($a[$n], $b[$n]) === 0) $n++;
            return $n;
        };

        // (a) a page route that is a dotted prefix of this name — longest wins.
        $hits = array_filter(array_map(fn ($c) => $c + ['score' => str_starts_with($name, $c['name'] . '.') ? strlen($c['name']) : 0], $cands), fn ($c) => $c['score'] > 0);
        if ($hits) return [$pick($hits, '/index|list/i'), 'name-prefix'];

        // (b) a page served by the same controller — its index/list menu page first.
        $hits = array_filter(array_map(fn ($c) => $c + ['score' => 1], $cands), fn ($c) => $c['class'] === $class && $class !== '');
        if ($hits) return [$pick($hits, '/index|list/i'), 'controller'];

        // (a') longest shared dotted name prefix of 2+ segments (resort.budget.*, people.promotion.*).
        $hits = array_filter(array_map(fn ($c) => $c + ['score' => $common($seg, explode('.', $c['name']))], $cands), fn ($c) => $c['score'] >= 2);
        if ($hits) return [$pick($hits, '/dashboard/i'), 'shared-name-prefix'];

        // (c) longest shared URL prefix of 2+ segments (resort/payroll/...), module dashboard preferred.
        // A verb as the first segment (resort/get/..., resort/update/...) says nothing about the module.
        $generic = in_array(strtolower($uri[1] ?? ''), ['get', 'update', 'store', 'save', 'delete', 'destroy', 'search', 'mark', 'add', 'send'], true);
        $hits = array_filter(array_map(fn ($c) => $c + ['score' => $common($uri, $c['uri'])], $cands), fn ($c) => $c['score'] >= ($generic ? 3 : 2));
        if ($hits) return [$pick($hits, '/dashboard/i'), 'url-prefix'];

        // (d) a page served from the same controller module folder (Resorts\Learning\*), module dashboard preferred.
        $ns = substr($class, 0, (int) strrpos($class, '\\'));
        $hits = array_filter(array_map(fn ($c) => $c + ['score' => 1], $cands), fn ($c) => $ns !== 'App\\Http\\Controllers\\Resorts' && $ns !== ''
            && str_starts_with($c['class'], $ns . '\\'));
        if ($hits) return [$pick($hits, '/dashboard/i'), 'controller-folder'];

        return [null, 'none'];
    }

    public static function inferTick(string $name, Route $route): string
    {
        $methods = $route->methods();
        if (in_array('GET', $methods, true)) {
            return 'view';   // incl. downloads/exports; the middleware only ever asks View anyway
        }
        $last = substr($name, strrpos($name, '.') !== false ? strrpos($name, '.') + 1 : 0);
        $words = array_map('strtolower', preg_split('/[^A-Za-z]+|(?<=[a-z])(?=[A-Z])/', $last . ' ' . self::controller($route)[1], -1, PREG_SPLIT_NO_EMPTY));
        $has = fn (array $set) => (bool) array_intersect($words, $set);

        if (in_array(strtolower($words[0] ?? ''), ['get', 'fetch', 'list', 'show', 'view', 'search', 'filter', 'load', 'export', 'download', 'print', 'preview', 'check', 'calculate', 'count'], true)) {
            return 'view';
        }
        if (in_array('DELETE', $methods, true) || $has(['destroy', 'destory', 'delete', 'remove', 'massremove', 'trash'])) return 'delete';
        if ($has(['store', 'create', 'add', 'new', 'import', 'upload', 'duplicate', 'clone'])) return 'create';
        if ($has(['update', 'edit', 'save', 'status', 'approve', 'reject', 'assign', 'send', 'restore', 'archive', 'toggle', 'cancel', 'close', 'submit'])) return 'edit';
        if ($has(['get', 'fetch', 'list', 'show', 'view', 'search', 'filter', 'details', 'detail', 'data', 'export', 'download', 'print', 'preview', 'report', 'chart', 'datatable', 'grid', 'history', 'run', 'insights'])) return 'view';
        return 'edit';   // unknown write: needs Edit, the safer default for a state-changing method
    }

    /** [FQCN, method] or ['', ''] for closures. */
    public static function controller(Route $route): array
    {
        $action = $route->getActionName();
        return str_contains($action, '@') ? explode('@', $action, 2) : ['', ''];
    }
}
